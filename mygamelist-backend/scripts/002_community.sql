 target_type varchar(20) NOT NULL, target_id bigint NOT NULL,
 reason varchar(32) NOT NULL, details varchar(2000) NOT NULL,
 snapshot varchar(2000) NOT NULL, status varchar(20) NOT NULL,
 created_at timestamp NOT NULL, reviewed_at timestamp,
 reviewer_id bigint, moderator_note varchar(2000),
 UNIQUE(reporter_id,target_type,target_id)
);
