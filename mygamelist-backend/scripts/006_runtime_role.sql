\getenv runtime_password MGL_RUNTIME_PASSWORD
BEGIN;
SELECT 'CREATE ROLE mygamelist_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS'
WHERE NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='mygamelist_app')
\gexec
SELECT format('ALTER ROLE mygamelist_app WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD %L', :'runtime_password')
\gexec
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT CONNECT ON DATABASE mygamelist TO mygamelist_app;
GRANT USAGE ON SCHEMA public TO mygamelist_app;
GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA public TO mygamelist_app;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO mygamelist_app;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public GRANT SELECT,INSERT,UPDATE,DELETE ON TABLES TO mygamelist_app;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public GRANT USAGE,SELECT ON SEQUENCES TO mygamelist_app;
ALTER ROLE mygamelist_app SET statement_timeout='10s';
ALTER ROLE mygamelist_app SET lock_timeout='5s';
ALTER ROLE mygamelist_app SET idle_in_transaction_session_timeout='15s';
COMMIT;
